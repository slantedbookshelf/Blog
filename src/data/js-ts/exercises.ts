import type { Exercise } from './types';

function exercise(
  title: string, difficulty: Exercise['difficulty'], signature: string,
  task: string, constraints: string, hint: string, body: string, explanation: string,
): Exercise {
  return {
    title, difficulty, task, constraints, hint, explanation,
    starter: signature + "\n  throw new Error('请实现 solve');\n}",
    solution: signature + '\n' + body + '\n}',
  };
}

