import { importsBlock, type GoImport } from './source';

function exercise(
  title: string, difficulty: Exercise['difficulty'], signature: string, task: string,
  constraints: string, hint: string, body: string, explanation: string, imports: GoImport[] = [],
): Exercise {
  const prefix = 'package main\n\n';
  return {
    title, difficulty, task, constraints, hint, explanation,
    starter: prefix + signature + '\n\tpanic("请实现 solve")\n}',
    solution: prefix + importsBlock(imports) + signature + '\n' + body + '\n}',
  };
}

